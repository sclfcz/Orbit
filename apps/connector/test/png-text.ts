const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = CRC_TABLE[(crc ^ byte) & 0xff]! ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Buffer): Buffer {
  const length = Buffer.alloc(4); length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

/** White background, black glyphs; `scale` pixels per font pixel. */
export function textPng(text: string, scale = 10): Buffer {
  const cols = 7; // 5 glyph columns + 2 gap
  const width = 24 + text.length * cols * scale;
  const height = 24 + 7 * scale;
  const pixels = Buffer.alloc(width * height * 3, 0xff); // RGB, white
  [...text.toUpperCase()].forEach((character, index) => {
    const glyph = GLYPHS[character] ?? GLYPHS["0"]!;
    glyph.forEach((row, y) => {
      [...row].forEach((bit, x) => {
        if (bit !== "1") return;
        for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
          const px = 12 + (index * cols + x) * scale + dx;
          const py = 12 + y * scale + dy;
          const offset = (py * width + px) * 3;
          pixels[offset] = 0; pixels[offset + 1] = 0; pixels[offset + 2] = 0;
        }
      });
    });
  });
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0); header.writeUInt32BE(height, 4);
  header[8] = 8; header[9] = 2; // 8-bit RGB
  const scanlines = Buffer.alloc((width * 3 + 1) * height);
  for (let y = 0; y < height; y++) {
    pixels.copy(scanlines, y * (width * 3 + 1) + 1, y * width * 3, (y + 1) * width * 3);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(scanlines)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
